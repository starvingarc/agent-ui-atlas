#!/usr/bin/env python3
"""Render the human-facing README files from catalog.yaml."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
CATALOG_PATH = ROOT / "catalog.yaml"

CATEGORIES = [
    ("brand", "brand-and-product-styles", "🔖 Brand and Product Styles", "🔖 品牌与产品风格"),
    ("general", "general-ui-design-languages", "🎨 General UI Design Languages", "🎨 通用 UI 设计语言"),
    ("game_ip_scene", "game-ip-and-scene-themes", "🎮 Game, IP, and Scene Themes", "🎮 游戏、IP 与场景主题"),
    ("reference", "reference-interfaces", "🧠 Reference Interfaces", "🧠 参考型界面"),
    ("image_layer", "image-layers", "🖼️ Image Layers", "🖼️ 图像素材层"),
    ("motion_layer", "motion-layers", "✨ Motion Layers", "✨ 动效层"),
]


def load_catalog() -> dict:
    with CATALOG_PATH.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def localized(value, lang: str):
    if isinstance(value, dict):
        return value[lang]
    return value


def cell(value: str) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def prose_list(values: list[str], lang: str) -> str:
    separator = "、" if lang == "zh" else ", "
    return separator.join(cell(item) for item in values)


def resource_links(resources: list[dict], lang: str) -> str:
    links = []
    for resource in resources:
        label = localized(resource["label"], lang)
        links.append(f"[{cell(label)}]({resource['url']})")
    return " · ".join(links)


PREVIEW_KINDS = {
    "interactive_demo": {"en": "Interactive demo", "zh": "交互演示"},
    "showcase": {"en": "Showcase", "zh": "风格展示"},
    "live_site": {"en": "Live website", "zh": "真实网站"},
}


def preview_links(record: dict, lang: str) -> str:
    previews = record.get("previews", [])
    if not previews:
        return "暂未收录" if lang == "zh" else "Not yet listed"
    return " · ".join(
        f"[{cell(p['label'][lang])}]({p['url']}) ({PREVIEW_KINDS[p['kind']][lang]})"
        for p in previews
    )


def preview_hub_rows(catalog: dict, lang: str) -> list[str]:
    return [
        f"| {cell(hub['name'])} | {cell(hub['summary'][lang])} | {preview_links(hub, lang)} |"
        for hub in catalog.get("preview_hubs", [])
    ]


def style_rows(catalog: dict, category: str, lang: str) -> list[str]:
    rows = []
    styles = sorted(
        (style for style in catalog["styles"] if style["category"] == category),
        key=lambda style: style["sort_key"].casefold(),
    )
    for style in styles:
        name = cell(style["name"][lang])
        aliases = prose_list(style["aliases"][lang], lang)
        cues = prose_list(style["visual_cues"][lang], lang)
        best_for = prose_list(style["best_for"][lang], lang)
        resources = resource_links(style["resources"], lang)
        rows.append(f"| {name} | {aliases} | {cues} | {best_for} | {preview_links(style, lang)} | {resources} |")
    return rows


def quick_pick_rows(catalog: dict, lang: str, style_index: dict[str, dict]) -> list[str]:
    rows = []
    for group in catalog["quick_picks"]:
        links = []
        for style_id in group["style_ids"]:
            style = style_index[style_id]
            label = style["name"][lang]
            resource = next((r for r in style["resources"] if r.get("canonical")), style["resources"][0])
            if style.get("previews"):
                url = style["previews"][0]["url"]
                spec = "规范" if lang == "zh" else "spec"
                links.append(f"[{cell(label)}]({url}) ([{spec}]({resource['url']}))")
            else:
                links.append(f"[{cell(label)}]({resource['url']})")
        rows.append(f"| {cell(group['label'][lang])} | {' · '.join(links)} |")
    return rows


def skill_rows(catalog: dict, lang: str) -> list[str]:
    rows = []
    for skill in catalog["skills"]:
        roles = prose_list(skill["roles"][lang], lang)
        summary = cell(skill["summary"][lang])
        rows.append(f"| {cell(skill['name'])} | {roles} | {summary} | {preview_links(skill, lang)} | [Skill]({skill['url']}) |")
    return rows


def render(catalog: dict, lang: str) -> str:
    zh = lang == "zh"
    style_index = {style["id"]: style for style in catalog["styles"]}
    counts = {key: sum(style["category"] == key for style in catalog["styles"]) for key, *_ in CATEGORIES}
